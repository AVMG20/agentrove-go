func TestNftRulesetGolden(t *testing.T) {
	got, err := nftRuleset(sampleEgressPolicy())
	if err != nil {
		t.Fatal(err)
	}
	if got != goldenInet {
		t.Errorf("inet ruleset differs:\n%s", diffLines(goldenInet, got))
	}
	br, err := nftBridgeRuleset(sampleEgressPolicy())
	if err != nil {
		t.Fatal(err)
	}
	if br != goldenBridge {
		t.Errorf("bridge ruleset differs:\n%s", diffLines(goldenBridge, br))
	}
}

func diffLines(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	var b strings.Builder
	for i := 0; i < len(w) || i < len(g); i++ {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			b.WriteString("- " + wl + "\n+ " + gl + "\n")
		}
	}
	return b.String()
}

