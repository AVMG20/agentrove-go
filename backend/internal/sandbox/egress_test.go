type egressCall struct {
	script string
	env    map[string]string
}

// testFirewall installs a firewall on d whose helper runs are recorded.
func testFirewall(t *testing.T, d *DockerProvider, mode egressMode) (*egressFirewall, *[]egressCall, *error) {
	t.Helper()
	var calls []egressCall
	var fail error
	fw := &egressFirewall{mode: mode, table: egressTableName(d.instance()), covered: map[string]bool{},
		resolvConf: func() ([]byte, error) { return []byte("nameserver 127.0.0.11\n# ExtServers: [10.0.0.2]\n"), nil }}
	fw.run = func(_ context.Context, script string, env []string) (string, error) {
		m := map[string]string{}
		for _, kv := range env {
			k, v, _ := strings.Cut(kv, "=")
			m[k] = v
		}
		calls = append(calls, egressCall{script, m})
		if fail != nil {
			return "nft: boom", fail
		}
		return "agentrove-egress: applied", nil
	}
	egressStates.Store(d, fw)
	t.Cleanup(func() { egressStates.Delete(d) })
	return fw, &calls, &fail
}

func bridgeOf(name string) string { return "br-" + fakeNetID(name)[:12] }

func TestEgressCollect(t *testing.T) {
	d, f := newNetProvider(true, "", "abcdef123456")
	f.subnets["agentrove-sandbox-net"] = "172.18.0.0/16"
	f.ips["agentrove-sandbox-net"] = map[string]string{apiID: "172.18.0.2"}
	// This instance's network with a custom bridge name, another
	// instance's, and a non-bridge one.
	mine := UserNetworkName("ffff")
	f.networks[mine], f.labels[mine], f.subnets[mine] = map[string]bool{}, d.userNetworkLabels("ffff"), "10.99.0.0/24"
	f.options[mine] = map[string]string{"com.docker.network.bridge.name": "agbox-ffff"}
	other := UserNetworkName("eeee")
	f.networks[other], f.labels[other] = map[string]bool{}, map[string]string{ManagedLabel: "true", InstanceLabel: "other", UserLabel: "eeee"}
	overlay := UserNetworkName("dddd")
	f.networks[overlay], f.labels[overlay], f.drivers[overlay] = map[string]bool{}, d.userNetworkLabels("dddd"), "overlay"
	fw, _, _ := testFirewall(t, d, egressOn)

	p := d.egressCollect(context.Background(), fw)
	byName := map[string]egressNet{}
	for _, n := range p.Nets {
		byName[n.Name] = n
	}
	if len(byName) != 2 {
		t.Fatalf("nets = %+v", p.Nets)
	}
	shared := byName["agentrove-sandbox-net"]
	if shared.Bridge != bridgeOf("agentrove-sandbox-net") || !reflect.DeepEqual(shared.Trusted, []netip.Addr{mustAddr("172.18.0.2")}) ||
		!reflect.DeepEqual(shared.API, shared.Trusted) {
		t.Errorf("shared = %+v", shared)
	}
	if n := byName[mine]; n.Bridge != "agbox-ffff" || len(n.Trusted) != 0 || n.Subnets[0] != mustPrefix("10.99.0.0/24") {
		t.Errorf("user net = %+v", n)
	}
	if !reflect.DeepEqual(p.DNS, []netip.Addr{mustAddr("10.0.0.2")}) || p.DNSAny {
		t.Errorf("dns = %v %v", p.DNS, p.DNSAny)
	}
	if p.Table != "agentrove_box_"+d.instance() {
		t.Errorf("table = %s", p.Table)
	}
	fw.resolvConf = func() ([]byte, error) { return nil, errors.New("nope") }
	if p := d.egressCollect(context.Background(), fw); !p.DNSAny {
		t.Error("unknown DNS upstreams must allow port 53 rather than break DNS")
	}
}

func TestEgressCoversNetworkBeforeBoxStarts(t *testing.T) {
	d, f := newNetProvider(true, "", "abcdef123456")
	_, calls, fail := testFirewall(t, d, egressOn)
	ctx := context.Background()

	name := d.boxNetwork(ctx, netUser)
	if len(*calls) != 1 {
		t.Fatalf("helper runs = %d", len(*calls))
	}
	c := (*calls)[0]
	if !strings.Contains(c.env["AGENTROVE_NFT"], `iifname "`+bridgeOf(name)+`" jump box_egress`) {
		t.Fatalf("new network not in ruleset:\n%s", c.env["AGENTROVE_NFT"])
	}
	sub := f.subnets[name]
	if !strings.Contains(c.env["AGENTROVE_NFT_BRIDGE"], "ip saddr { "+sub+" } ip daddr { "+sub+" } tcp dport { 8080 } accept") {
		t.Fatalf("box -> API not allowed on its port:\n%s", c.env["AGENTROVE_NFT_BRIDGE"])
	}
	if strings.Contains(c.env["AGENTROVE_NFT"], "tcp dport { 8080 } accept") {
		t.Fatal("API in a container: the host's port must stay closed to boxes")
	}
	if !strings.Contains(c.script, `nft -f -`) || strings.Contains(c.script, "nft -c") {
		t.Fatalf("script = %s", c.script)
	}
	// Covered: no more helper runs for this network.
	d.boxNetwork(ctx, netUser)
	if len(*calls) != 1 {
		t.Fatalf("re-applied for a covered network: %d runs", len(*calls))
	}
	// A failing apply leaves the next network uncovered and backs off.
	*fail = errors.New("exit 1")
	user2 := "0a1b2c3d-0000-4000-8000-000000000002"
	d.boxNetwork(ctx, user2)
	d.boxNetwork(ctx, user2)
	if len(*calls) != 2 {
		t.Fatalf("no backoff after failure: %d runs", len(*calls))
	}
	fw := d.egress()
	fw.lastFail = time.Now().Add(-time.Minute)
	*fail = nil
	d.boxNetwork(ctx, user2)
	if len(*calls) != 3 || !fw.covered[UserNetworkName(user2)] || !fw.covered[name] {
		t.Fatalf("retry: runs=%d covered=%v", len(*calls), fw.covered)
	}
}

