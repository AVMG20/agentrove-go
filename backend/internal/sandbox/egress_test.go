func TestParseResolvConf(t *testing.T) {
	cases := []struct {
		name  string
		in    string
		want  []netip.Addr
		known bool
	}{
		{"docker 25+, VPC resolver", "# Generated by Docker Engine.\nnameserver 127.0.0.11\noptions ndots:0\n\n# Based on host file: '/run/systemd/resolve/resolv.conf' (internal resolver)\n# ExtServers: [10.0.0.2 1.1.1.1]\n# Overrides: []\n",
			[]netip.Addr{mustAddr("10.0.0.2"), mustAddr("1.1.1.1")}, true},
		{"docker 25+, host loopback", "nameserver 127.0.0.11\n# ExtServers: [host(127.0.0.53)]\n", []netip.Addr{}, true},
		{"old docker", "nameserver 127.0.0.11\noptions ndots:0\n", nil, false},
		{"api on host, plain servers", "nameserver 192.168.1.1\nnameserver 2001:4860:4860::8888\n", []netip.Addr{mustAddr("192.168.1.1"), mustAddr("2001:4860:4860::8888")}, true},
		{"api on host, systemd stub", "nameserver 127.0.0.53\n", nil, false},
		{"empty", "", nil, false},
	}
	for _, tc := range cases {
		got, known := parseResolvConf([]byte(tc.in))
		if known != tc.known || !reflect.DeepEqual(got, tc.want) {
			t.Errorf("%s: got %v %v, want %v %v", tc.name, got, known, tc.want, tc.known)
		}
	}
}

